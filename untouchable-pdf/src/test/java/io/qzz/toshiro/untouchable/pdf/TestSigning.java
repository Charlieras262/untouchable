package io.qzz.toshiro.untouchable.pdf;

import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.math.BigInteger;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.cert.X509Certificate;
import java.util.Calendar;
import java.util.Collections;
import java.util.Date;

import javax.imageio.ImageIO;

import org.apache.pdfbox.Loader;
import org.apache.pdfbox.cos.COSName;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.interactive.digitalsignature.PDSignature;
import org.apache.pdfbox.pdmodel.interactive.digitalsignature.SignatureInterface;
import org.apache.pdfbox.pdmodel.interactive.digitalsignature.SignatureOptions;
import org.apache.pdfbox.pdmodel.interactive.digitalsignature.visible.PDVisibleSigProperties;
import org.apache.pdfbox.pdmodel.interactive.digitalsignature.visible.PDVisibleSignDesigner;
import org.apache.pdfbox.pdmodel.interactive.form.PDSignatureField;
import org.bouncycastle.asn1.x500.X500Name;
import org.bouncycastle.cert.jcajce.JcaCertStore;
import org.bouncycastle.cert.jcajce.JcaX509CertificateConverter;
import org.bouncycastle.cert.jcajce.JcaX509v3CertificateBuilder;
import org.bouncycastle.cms.CMSProcessableByteArray;
import org.bouncycastle.cms.CMSSignedDataGenerator;
import org.bouncycastle.cms.jcajce.JcaSignerInfoGeneratorBuilder;
import org.bouncycastle.operator.jcajce.JcaContentSignerBuilder;
import org.bouncycastle.operator.jcajce.JcaDigestCalculatorProviderBuilder;

/** Test electronic signatures (as Acrobat would make them): self-signed RSA certificate and incremental save. */
final class TestSigning {
    static final KeyPair KEYS;
    static final X509Certificate CERT;

    static {
        try {
            KeyPairGenerator g = KeyPairGenerator.getInstance("RSA");
            g.initialize(2048);
            KEYS = g.generateKeyPair();
            X500Name name = new X500Name("CN=Test signer");
            long now = System.currentTimeMillis();
            JcaX509v3CertificateBuilder b = new JcaX509v3CertificateBuilder(name, BigInteger.valueOf(now),
                    new Date(now - 86400000L), new Date(now + 86400000L * 365), name, KEYS.getPublic());
            CERT = new JcaX509CertificateConverter().getCertificate(
                    b.build(new JcaContentSignerBuilder("SHA256withRSA").build(KEYS.getPrivate())));
        } catch (Exception e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    private TestSigning() {}

    /** Signs an existing (empty) field of the document. */
    static byte[] signField(byte[] pdf, String fieldName) throws IOException {
        PDDocument doc = Loader.loadPDF(pdf);
        try {
            PDSignatureField field = (PDSignatureField) doc.getDocumentCatalog().getAcroForm(null).getField(fieldName);
            PDSignature sig = signature();
            field.getCOSObject().setItem(COSName.V, sig);
            return sign(doc, sig);
        } finally {
            doc.close();
        }
    }

    /**
     * New visible signature on page 1, with an appearance (image) generated by PDFBox, like an Acrobat
     * signature. {@code rect} is in PDF points (origin at the bottom left).
     */
    static byte[] signNewVisibleField(byte[] pdf, String fieldName, PDRectangle rect) throws IOException {
        PDDocument doc = Loader.loadPDF(pdf);
        try {
            BufferedImage img = new BufferedImage(Math.round(rect.getWidth()), Math.round(rect.getHeight()), BufferedImage.TYPE_INT_RGB);
            Graphics2D g = img.createGraphics();
            g.setColor(new Color(220, 230, 255));
            g.fillRect(0, 0, img.getWidth(), img.getHeight());
            g.setColor(Color.BLUE);
            g.drawString(fieldName, 5, 15);
            g.dispose();
            ByteArrayOutputStream png = new ByteArrayOutputStream();
            ImageIO.write(img, "png", png);

            float pageHeight = doc.getPage(0).getMediaBox().getHeight();
            PDVisibleSignDesigner designer = new PDVisibleSignDesigner(doc, new ByteArrayInputStream(png.toByteArray()), 1);
            designer.xAxis(rect.getLowerLeftX()).yAxis(pageHeight - rect.getUpperRightY())
                    .width(rect.getWidth()).height(rect.getHeight());
            PDVisibleSigProperties props = new PDVisibleSigProperties();
            props.signerName("Test signer").page(1).visualSignEnabled(true).setPdVisibleSignature(designer);
            props.buildSignature();

            SignatureOptions options = new SignatureOptions();
            try {
                options.setVisualSignature(props.getVisibleSignature());
                options.setPage(0);
                return sign(doc, signature(), options);
            } finally {
                options.close();
            }
        } finally {
            doc.close();
        }
    }

    /** New invisible signature (PDFBox creates the field). */
    static byte[] signInvisible(byte[] pdf) throws IOException {
        PDDocument doc = Loader.loadPDF(pdf);
        try {
            return sign(doc, signature());
        } finally {
            doc.close();
        }
    }

    private static PDSignature signature() {
        PDSignature sig = new PDSignature();
        sig.setFilter(PDSignature.FILTER_ADOBE_PPKLITE);
        sig.setSubFilter(PDSignature.SUBFILTER_ADBE_PKCS7_DETACHED);
        sig.setName("Test signer");
        sig.setSignDate(Calendar.getInstance());
        return sig;
    }

    private static byte[] sign(PDDocument doc, PDSignature sig) throws IOException {
        SignatureOptions options = new SignatureOptions();
        try {
            return sign(doc, sig, options);
        } finally {
            options.close();
        }
    }

    private static byte[] sign(PDDocument doc, PDSignature sig, SignatureOptions options) throws IOException {
        doc.addSignature(sig, new SignatureInterface() {
            @Override
            public byte[] sign(InputStream content) throws IOException {
                try {
                    CMSSignedDataGenerator gen = new CMSSignedDataGenerator();
                    gen.addSignerInfoGenerator(new JcaSignerInfoGeneratorBuilder(new JcaDigestCalculatorProviderBuilder().build())
                            .build(new JcaContentSignerBuilder("SHA256withRSA").build(KEYS.getPrivate()), CERT));
                    gen.addCertificates(new JcaCertStore(Collections.singletonList(CERT)));
                    return gen.generate(new CMSProcessableByteArray(Hashes.readAll(content)), false).getEncoded();
                } catch (Exception e) {
                    throw new IOException(e);
                }
            }
        }, options);
        ByteArrayOutputStream bos = new ByteArrayOutputStream();
        doc.saveIncremental(bos);
        return bos.toByteArray();
    }
}
